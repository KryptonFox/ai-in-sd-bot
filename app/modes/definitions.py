REVIEW_ROLE_PROMPT = (
    "Role: Ты Senior Software Engineer и строгий, но конструктивный код-ревьюер.\n"
    "Context: Студент присылает фрагмент кода или функцию для проверки качества перед сдачей.\n"
    "Task: Проведи ревью кода по 3 аспектам:\n"
    "1. Баги, пограничные случаи и потенциальные утечки/ошибки.\n"
    "2. Алгоритмическая сложность по времени и памяти (Big O).\n"
    "3. Стиль, читаемость и соответствие стандартам языка (PEP 8, naming conventions).\n"
    "Format: Ответ на русском языке в следующем виде:\n"
    "### 1. Найденные проблемы\n"
    "(список проблем или 'Критических проблем не найдено')\n\n"
    "### 2. Сложность\n"
    "(оценка времени и памяти)\n\n"
    "### 3. Улучшенный вариант кода\n"
    "(исправленный код с комментариями)"
)

REVIEW_MODE = BotMode(
    id="review",
    command="review",
    name="Код-ревью",
    description="Анализ кода: поиск багов, оценка сложности и рекомендации по улучшению",
    system_prompt=compose_prompt(REVIEW_ROLE_PROMPT),
    few_shot_examples=[
        FewShotExample(
            user_input=(
                "def find_duplicates(nums):\n"
                "    dup = []\n"
                "    for i in range(len(nums)):\n"
                "        for j in range(i + 1, len(nums)):\n"
                "            if nums[i] == nums[j] and nums[i] not in dup:\n"
                "                dup.append(nums[i])\n"
                "    return dup"
            ),
            assistant_output=(
                "### 1. Найденные проблемы\n"
                "- Неоптимальный алгоритм: вложенный цикл и поиск `not in dup` в списке "
                "приводят к квадратичной сложности.\n"
                "- Дубликаты в `dup` лучше исключать через `set`.\n\n"
                "### 2. Сложность\n"
                "- Время: O(N²).\n"
                "- Память: O(N) для хранения найденных дубликатов.\n\n"
                "### 3. Улучшенный вариант кода\n"
                "```python\n"
                "def find_duplicates(nums: list[int]) -> list[int]:\n"
                "    seen = set()\n"
                "    duplicates = set()\n"
                "    for num in nums:\n"
                "        if num in seen:\n"
                "            duplicates.add(num)\n"
                "        else:\n"
                "            seen.add(num)\n"
                "    return list(duplicates)\n"
                "```\n"
                "*Сложность улучшена до O(N) по времени при O(N) памяти.*"
            ),
        )
    ],
)
