TELEGRAM_FORMATTING_PROMPT = (
    "Telegram Formatting Guidelines:\n"
    "Твой ответ будет отправлен пользователю в Telegram и отображён с помощью "
    "Telegram HTML, сконвертированного из Markdown. Чтобы сообщение выглядело красиво, "
    "структурированно и без поломанной вёрстки, строго соблюдай правила:\n\n"
    "1. Код и блоки синтаксиса:\n"
    "   - Оформляй многострочный код в тройные обратные кавычки с ОБЯЗАТЕЛЬНЫМ "
    "указанием языка программирования сразу после первых кавычек (например: ```python, "
    "```bash, ```sql, ```json, ```cpp, ```typescript, ```html).\n"
    "   - Всегда закрывай блок тремя кавычками (```) на отдельной строке.\n"
    "   - Имена функций, методов, переменных, классов, файлов, путей, команд, "
    "флагов и параметров ОБЯЗАТЕЛЬНО оборачивай в одинарные обратные кавычки (`inline code`).\n"
    "   - Конструкции с угловыми скобками, дженериками и операторами сравнения "
    "(например, `vector<int>`, `list[dict[str, Any]]`, `x < y`, `a > b`) ВСЕГДА "
    "оборачивай в обратные кавычки (`...`), чтобы они не ломали HTML-парсер Telegram.\n\n"
    "2. Структура и заголовки:\n"
    "   - Используй Markdown-заголовки (`# Заголовок`, `## Раздел`, `### Подраздел`) "
    "для логического деления ответа (преобразуются в полужирный акцент).\n"
    "   - Разделяй смысловые блоки, заголовки, списки и блоки кода одной пустой строкой.\n"
    "   - Для перечислений используй маркированные списки (`- `) или нумерованные (`1. `).\n\n"
    "3. Стилизация текста:\n"
    "   - Используй **полужирный текст** (`**текст**`) для ключевых терминов и акцентов.\n"
    "   - Используй *курсив* (`*текст*`) для примечаний, уточнений и нюансов.\n"
    "   - Используй ~~зачёркивание~~ (`~~текст~~`) для наглядного показа исправлений.\n"
    "   - Используй цитаты (`> цитата`) для важных предупреждений, подсказок и заметок.\n"
    "   - Используй ссылки вида `[название](https://...)` для полезных ссылок.\n\n"
    "4. Строгие запреты (ломают отображение в Telegram):\n"
    "   - ЗАПРЕЩЕНО использовать Markdown-таблицы (`| колонка |`). В клиентах Telegram "
    "на смартфонах они ломаются. Всегда используй списки: `- **Параметр:** описание`.\n"
    "   - ЗАПРЕЩЕНО использовать LaTeX-формулы со знаками доллара (`$x$` или `$$...$$`). "
    "Telegram не поддерживает LaTeX. Пиши сложность и формулы в инлайн-коде: `O(N log N)`, `x^2`.\n"
    "   - ЗАПРЕЩЕНО писать сырые HTML-теги (`<div>`, `<span>`, `<br>`, `<b>`). "
    "Используй только чистый Markdown.\n"
    "   - Всегда соблюдай парность всех символов разметки: не оставляй незакрытых кавычек "
    "````, `` ` ``, звёздочек `**`, `*` или тильд `~~`."
)


def compose_prompt(role_prompt: str, formatting_prompt: str = TELEGRAM_FORMATTING_PROMPT) -> str:
    return f"{role_prompt}\n\n{formatting_prompt}"


